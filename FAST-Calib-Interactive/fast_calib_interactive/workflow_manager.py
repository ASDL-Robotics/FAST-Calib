# Helpers
# ---------------------------------------------------------------------------

def _parse_result_matrix(path: Path) -> np.ndarray:
    """Parse Rcl and Pcl from a fast_calib result file into a 4x4 matrix.

    Expected format (FAST-LIVO2):
        Rcl: [ r00, r01, r02,
               r10, r11, r12,
               r20, r21, r22]
        Pcl: [ tx, ty, tz]
    """
    text = path.read_text()
    raw = yaml.safe_load(text)

    rcl = raw.get('Rcl') or raw.get('rcl')
    pcl = raw.get('Pcl') or raw.get('pcl')

    if rcl is None or pcl is None:
        raise ValueError(f'Could not find Rcl/Pcl in {path}')

    R = np.array(rcl, dtype=float).reshape(3, 3)
    t = np.array(pcl, dtype=float).reshape(3, 1)

    T = np.eye(4)
    T[:3, :3] = R
    T[:3, 3] = t[:, 0]
    return T
